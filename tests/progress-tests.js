globalThis.runReaderProgressTests = async function () {
  const results=[];
  const check=(name,passed,details)=>results.push({name,passed:!!passed,...(!passed?{details}: {})});
  const wait=()=>new Promise(r=>setTimeout(r,250));
  const source=document.querySelector('#source');
  const root=document.querySelector('#first [data-book-reader="host"]').shadowRoot;
  const entry=document.querySelector('[data-book-reader="entry"]').shadowRoot;
  if(root.querySelector('.reader'))root.querySelector('[data-action=close]').click();
  const paragraph=source.querySelectorAll('p')[9];
  paragraph.scrollIntoView({block:'start',behavior:'instant'});window.scrollBy({top:100,behavior:'instant'});
  source.dispatchEvent(new PointerEvent('pointerover',{bubbles:true}));
  const caret=document.caretRangeFromPoint(source.getBoundingClientRect().left+12,105);
  const point=caret.startContainer,pointOffset=caret.startOffset;
  const before=scrollY;
  const prefix=document.createRange();prefix.selectNodeContents(source);prefix.setEnd(point,pointOffset);
  const expectedOffset=prefix.toString().length;
  entry.querySelector('.launch').click();await wait();
  const papers=[...root.querySelectorAll('.spread .paper-content')];
  const starts=papers.flatMap(n=>[...n.children]).map(n=>Number(n.dataset.bookOffset));
  const last=papers.at(-1).lastElementChild;
  const end=Number(last.dataset.bookOffset)+last.textContent.length;
  check('从长文中段打开，当前文字位于书页内',Math.min(...starts)<=expectedOffset && end>expectedOffset,{starts,end,expectedOffset});
  check('没有跳回第一页',!root.querySelector('.position').textContent.startsWith('1–') && !root.querySelector('.position').textContent.startsWith('1 /'));
  check('界面无副标题、常驻说明或重复页码',!root.querySelector('.edition,.hint,.settings-note,.folio,.progress'));
  entry.querySelector('.launch').click();await wait();
  const afterRange=document.createRange();afterRange.setStart(point,pointOffset);afterRange.setEnd(point,Math.min(point.length,pointOffset+1));
  check('原地退出回到相同文字附近',Math.abs(afterRange.getBoundingClientRect().top-80)<50,{before,after:scrollY,pointTop:afterRange.getBoundingClientRect().top});
  // Exercise the same runtime message that the toolbar action sends.
  const runtimeOpen=()=>new Promise(resolve=>__readerRuntimeListener({type:'book-reader:open'},{},resolve));
  const response=await runtimeOpen();await wait();
  check('工具栏消息可以从当前位置开启',response.ok && !!root.querySelector('.reader'));
  const initial=root.querySelector('.position').textContent;
  root.querySelector('[data-action=next]').click();
  check('开启后可继续向后阅读',initial!==root.querySelector('.position').textContent);
  const selected=root.querySelector('.spread .paper-content > [data-book-offset]');
  const currentOffset=Number(selected.dataset.bookOffset);
  const currentText=selected.textContent;
  await runtimeOpen();await wait();
  check('工具栏消息可以退出模式',!root.querySelector('.reader'));
  check('翻页后退出保留新的进度',scrollY>before+30,{before,after:scrollY,currentOffset});
  await runtimeOpen();await wait();
  const reopened=[...root.querySelectorAll('.spread .paper-content')].map(n=>n.textContent).join('');
  check('再次开启仍在刚才阅读的内容附近',reopened.includes(currentText.slice(0,25)),{expected:currentText.slice(0,25),actual:reopened.slice(0,100)});
  root.querySelector('[data-action=close]').click();
  // Current ChatGPT uses this exact semantic marker and no legacy selectors.
  const modern=document.createElement('div');modern.setAttribute('data-markdown-text-style','assistant-message');modern.innerHTML='<p>新的回答结构</p><p>人物：<button>实体名字必须保留</button>。</p>';
  document.querySelector('main').append(modern);await wait();
  check('识别真实页面采用的新结构',modern.previousElementSibling?.dataset.bookReader==='host');
  const extracted=BookPaginator.extract(modern);
  check('保留正文内可点击实体的文字',extracted.map(n=>n.textContent).join('').includes('实体名字必须保留') && extracted.every(n=>!n.querySelector('button')));
  modern.remove();await wait();
  const streaming=document.createElement('div');streaming.setAttribute('data-markdown-text-style','assistant-message');const p=document.createElement('p');const text=document.createTextNode('');p.append(text);streaming.append(p);document.querySelector('main').append(streaming);
  const interval=setInterval(()=>{text.data+='字';},20);await wait();
  check('连续流式更新也能及时识别回答',streaming.previousElementSibling?.dataset.bookReader==='host');clearInterval(interval);streaming.remove();
  return {passed:results.filter(r=>r.passed).length,total:results.length,results};
};
