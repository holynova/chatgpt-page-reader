globalThis.runImmersiveTests = async function () {
  const results=[];
  const check=(name,passed,details)=>results.push({name,passed:!!passed,...(!passed?{details}: {})});
  const wait=ms=>new Promise(r=>setTimeout(r,ms||260));
  const source=document.querySelector('#source');
  source.scrollIntoView({block:'start',behavior:'instant'});window.scrollBy({top:-80,behavior:'instant'});
  document.querySelector('[data-book-reader=entry]').shadowRoot.querySelector('.launch').click();await wait();
  let root=document.querySelector('[data-book-reader=host][data-book-source=source]').shadowRoot;
  let rect=root.querySelector('.reader').getBoundingClientRect();
  const main=document.querySelector('main').getBoundingClientRect();
  check('普通模式占据大部分主内容区',rect.width>=main.width*.9 && rect.height>=innerHeight*.8,{width:rect.width,available:main.width,height:rect.height,viewport:innerHeight});
  root.querySelector('[data-action=ask]').click();
  check('追问框位于书页内部',!!root.querySelector('.reader .ask textarea') && root.querySelector('.ask').getBoundingClientRect().bottom<=rect.bottom);
  root.querySelector('[data-action=ask]').click();
  check('保留原生输入框节点',!!BookComposer.find() && !root.contains(BookComposer.find()));
  root.querySelector('[data-action=immersive]').click();await wait();
  rect=root.querySelector('.reader').getBoundingClientRect();
  check('沉浸模式覆盖整个网页',rect.left===0 && rect.top===0 && Math.abs(rect.width-innerWidth)<2 && Math.abs(rect.height-innerHeight)<2,rect.toJSON());
  check('默认收起目录以展示完整书页',root.querySelector('.catalog').hidden);
  root.querySelector('[data-action=catalog]').click();
  check('沉浸模式提供对话框语义',root.querySelector('.reader').getAttribute('aria-modal')==='true');
  check('当前回答的章节可导航',root.querySelectorAll('.catalog [data-offset]').length>=5);
  const chapter=[...root.querySelectorAll('.catalog [data-offset]')].find(n=>n.textContent.includes('二、'));
  chapter.click();
  check('点击章节定位到对应书页',root.querySelector('.spread').textContent.includes('二、不同阅读方式'));
  check('章节挂在对应轮次下',!!chapter.closest('.round-node'));
  const beforeToggle=root.querySelector('.spread').textContent.slice(0,20);
  root.querySelector('.book').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,composed:true,cancelable:true}));await wait();
  check('可返回普通模式并保留内容位置',root.querySelector('.reader').dataset.immersive==='false' && root.querySelector('.spread').textContent.includes(beforeToggle));
  root.querySelector('[data-action=immersive]').click();await wait();
  root.querySelector('[data-action=catalog]').click();await wait();
  check('目录以覆盖面板打开',!root.querySelector('.catalog').hidden && !root.querySelector('.panel-backdrop').hidden);
  root.querySelector('[data-action=catalog]').click();await wait();
  check('目录可收起',root.querySelector('.catalog').hidden);
  check('书目来自现有会话列表',root.querySelectorAll('.book-title').length>=3 && root.querySelector('.catalog-list').textContent.includes('一座花园'));
  const native=BookComposer.find();const setNative=text=>{if(native.tagName==='TEXTAREA')native.value=text;else native.textContent=text;};
  setNative('保留的原草稿');
  root.querySelector('[data-action=ask]').click();
  const ask=root.querySelector('.ask textarea');ask.value='请用一句话解释。\n保留换行。';ask.dispatchEvent(new Event('input',{bubbles:true}));
  root.querySelector('.ask button').click();await wait();
  check('不会覆盖ChatGPT原有草稿',__sentPrompts.length===0 && root.querySelector('.ask-status').textContent.includes('已有草稿') && ask.value.includes('一句话'));
  setNative('');
  root.querySelector('.ask button').click();await wait(1300);
  check('追问通过原生发送流程且只发送一次',__sentPrompts.length===1 && __sentPrompts[0]==='请用一句话解释。\n保留换行。',__sentPrompts);
  const active=[...document.querySelectorAll('[data-book-reader=host]')].find(n=>!!n.shadowRoot.querySelector('.reader'));
  root=active?.shadowRoot;
  check('新回答单独接到书内且维持沉浸模式',root?.querySelector('.reader').dataset.immersive==='true' && root.querySelector('.spread').textContent.includes('追问的新回答') && !root.querySelector('.spread').textContent.includes('让阅读，回到'));
  check('流式后续内容继续显示',root?.querySelector('.spread').textContent.includes('流式回答完成'));
  check('发送后书内输入框清空',root?.querySelector('.ask textarea').value==='');
  root.querySelector('[data-action=catalog]').click();
  const garden=[...root.querySelectorAll('.book-title')].find(n=>n.textContent.includes('一座花园'));
  const originalURL=location.href;
  garden.click();await wait(600);
  const after=[...document.querySelectorAll('[data-book-reader=host]')].find(n=>!!n.shadowRoot.querySelector('.reader'))?.shadowRoot;
  check('书目切换复用原会话链接',location.pathname==='/c/garden');
  check('切换会话后保持沉浸且不混合原回答',after?.querySelector('.reader').dataset.immersive==='true' && after.querySelector('.spread').textContent.includes('切换会话成功') && !after.querySelector('.spread').textContent.includes('追问的新回答'));
  check('切换会话不会发送消息',__sentPrompts.length===1);
  check('没有遗留多个打开的阅读器',[...document.querySelectorAll('[data-book-reader=host]')].filter(n=>n.shadowRoot.querySelector('.reader')).length===1);
  after.querySelector('[data-action=close]').click();history.replaceState(null,'',originalURL);
  return {passed:results.filter(r=>r.passed).length,total:results.length,results};
};
